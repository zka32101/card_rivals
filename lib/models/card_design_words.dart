/// カードデザイン選択状態を管理するモデル
class CardDesign {
  final List<String> selectedWords; // 3つまで選択可能
  final String? imageUrl; // AI生成イメージ

  CardDesign({
    required this.selectedWords,
    this.imageUrl,
  });

  bool get isComplete => selectedWords.length == 3;

  String get designDescription => selectedWords.join(' × ');
}
